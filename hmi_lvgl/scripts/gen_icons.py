#!/usr/bin/env python3
"""Rasterise assets/icons/*.svg (Lucide, ISC) into A8 alpha bitmaps at a few sizes: src/icons_gen.c.
Needs rsvg-convert and Pillow on the laptop; the generated C is committed so the Pi needs neither.
Usage: scripts/gen_icons.py [app-icon.png]   (the optional PNG becomes the 96 px ARGB About-screen logo)"""
import io
import subprocess
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent.parent
SIZES = (12, 16, 20, 24, 30, 40, 56, 84)
BASE = 5   # every icon has the first BASE sizes; the big ones only these:
BIG = {"scan-face", "shield-check", "circle-x", "circle-check", "audio-lines", "smartphone", "check", "mic", "flag", "store"}

def c_id(name): return name.replace("-", "_")

def main():
    svgs = sorted((HERE / "assets/icons").glob("*.svg"))
    out = ['/* generated by scripts/gen_icons.py - do not edit */', '#include "icons.h"', '']
    table = []
    for svg in svgs:
        text = svg.read_text().replace("currentColor", "#ffffff")
        for sz in (SIZES if svg.stem in BIG else SIZES[:BASE]):
            png = subprocess.run(["rsvg-convert", "-w", str(sz * 4), "-h", str(sz * 4), "-f", "png"],
                                 input=text.encode(), capture_output=True, check=True).stdout
            im = Image.open(io.BytesIO(png)).convert("RGBA").split()[3]
            im = im.resize((sz, sz), Image.LANCZOS)   # 4x supersample keeps thin strokes even
            data = im.tobytes()
            sym = f"ic_{c_id(svg.stem)}_{sz}"
            out.append(f"static const uint8_t {sym}_map[] = {{")
            for i in range(0, len(data), 24):
                out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
            out.append("};")
            out.append(f"static const lv_image_dsc_t {sym} = {{ .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, "
                       f".w = {sz}, .h = {sz}, .stride = {sz} }}, .data_size = {len(data)}, .data = {sym}_map }};")
        table.append(svg.stem)
    out.append("\nconst lv_image_dsc_t *dos_icon_src(dos_icon_t id, int *px)\n{")
    out.append("    static const lv_image_dsc_t *const T[DOS_ICON_COUNT][%d] = {" % len(SIZES))
    for n in table:
        out.append("        [DOS_IC_%s] = { %s }," % (c_id(n).upper(), ", ".join(f"&ic_{c_id(n)}_{s}" if (n in BIG or SIZES.index(s) < BASE) else "NULL" for s in SIZES)))
    out.append("    };")
    out.append("    static const int S[%d] = { %s };" % (len(SIZES), ", ".join(map(str, SIZES))))
    out.append("    int best = 0;\n    for(int i = 0; i < %d; i++) if(T[id][i] && S[i] <= *px) best = i;" % len(SIZES))
    out.append("    *px = S[best];\n    return T[id][best];\n}")
    out.append("\nconst char *const dos_icon_names[DOS_ICON_COUNT] = { %s };" % ", ".join('"%s"' % n for n in table))
    (HERE / "src/icons_gen.c").write_text("\n".join(out) + "\n")
    hdr = ['/* generated by scripts/gen_icons.py - do not edit */', "#pragma once", '#include "lvgl.h"', "typedef enum {"]
    hdr += ["    DOS_IC_%s," % c_id(n).upper() for n in table] + ["    DOS_ICON_COUNT", "} dos_icon_t;"]
    hdr.append("/* nearest generated size not larger than *px (updates *px) */")
    hdr.append("const lv_image_dsc_t *dos_icon_src(dos_icon_t id, int *px);")
    hdr.append("extern const char *const dos_icon_names[DOS_ICON_COUNT];")
    (HERE / "src/icons.h").write_text("\n".join(hdr) + "\n")
    print(f"{len(table)} icons x {len(SIZES)} sizes")
    if len(sys.argv) > 1:
        im = Image.open(sys.argv[1]).convert("RGBA").resize((96, 96), Image.LANCZOS)
        px = im.tobytes()
        # LVGL ARGB8888 is B,G,R,A bytes
        bgra = bytearray()
        for i in range(0, len(px), 4):
            r, g, b, a = px[i:i + 4]
            bgra += bytes((b, g, r, a))
        lines = ['/* generated by scripts/gen_icons.py from packaging/icon/drive-os-256.png */', '#include "lvgl.h"',
                 "static const uint8_t logo_map[] = {"]
        for i in range(0, len(bgra), 32):
            lines.append("  " + ",".join(str(b) for b in bgra[i:i + 32]) + ",")
        lines += ["};", "const lv_image_dsc_t dos_logo_96 = { .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, "
                  ".w = 96, .h = 96, .stride = 384 }, .data_size = %d, .data = logo_map };" % len(bgra)]
        (HERE / "src/logo_gen.c").write_text("\n".join(lines) + "\n")

main()
